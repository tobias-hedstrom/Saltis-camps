function campCosts(prefix, { boende = 0, lift = 0, bana = 0, coach = 6000, transport = 0, food = 0, admin = 800, buffert = 800 }) {
  return [
    boende > 0 && { id: `${prefix}-boende`, name: "Boende per åkare", category: "Boende", amount: boende, isFixed: false, notes: "Preliminär gruppbokning" },
    lift > 0 && { id: `${prefix}-lift`, name: "Liftkort per åkare", category: "Liftkort", amount: lift, isFixed: false, notes: "Preliminärt pris" },
    food > 0 && { id: `${prefix}-mat`, name: "Mat per åkare", category: "Mat", amount: food, isFixed: false, notes: "Preliminärt pris" },
    bana > 0 && { id: `${prefix}-bana`, name: "Bana och anläggning", category: "Banavgifter", amount: bana, isFixed: true, notes: "" },
    coach > 0 && { id: `${prefix}-coach`, name: "Tränararvoden", category: "Tränararvoden", amount: coach, isFixed: true, notes: "Preliminärt tränarupplägg" },
    transport > 0 && { id: `${prefix}-transport`, name: "Gemensam transport", category: "Transport", amount: transport, isFixed: true, notes: "Om gemensam resa bokas" },
    admin > 0 && { id: `${prefix}-admin`, name: "Administration", category: "Administration", amount: admin, isFixed: true, notes: "" },
    buffert > 0 && { id: `${prefix}-buffert`, name: "Buffert", category: "Buffert", amount: buffert, isFixed: true, notes: "Preliminär reserv" },
  ].filter(Boolean);
}

